const rot = ([x, y], n) => { for (let i = 0; i < n; i++) [x, y] = [-y, x]; return [x, y]; };
const DIR = { '0,1': '下', '-1,0': '左', '0,-1': '上', '1,0': '右' };
export function bendCases() {
  const out = [];
  for (let n = 0; n < 4; n++) for (const [name, pts, k, m] of base) {
    const ps = pts.map((p) => rot(p, n)).map(([x, y]) => ({ x: x + 0, y: y + 0 }));
    const d1 = rot([0, 1], n).map((v) => v + 0).join(',');
    out.push({ name: `d1 ${DIR[d1]}: ${name}`, points: ps, k, m });
  }
  return out;
}
